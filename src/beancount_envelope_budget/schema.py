# --- Lookups and rendering -----------------------------------------------------


def get_diagnostic(code: str) -> DiagnosticCode:
    """Return the registered diagnostic for a code.

    Args:
        code: The diagnostic code, such as ``E001``.

    Returns:
        The matching :class:`DiagnosticCode`.

    Raises:
        KeyError: If the code is not registered.
    """
    return _DIAGNOSTICS_BY_CODE[code]


def render_message(code: str, **fields: object) -> str:
    """Render a diagnostic summary with named fields.

    Args:
        code: The diagnostic code, such as ``E001``.
        **fields: Values for the summary template's placeholders.

    Returns:
        The formatted message.

    Raises:
        KeyError: If the code is not registered.

    Examples:
        >>> render_message("E001", name="Groceries")
        'Envelope Groceries is used but was never declared.'
    """
    return get_diagnostic(code).summary.format(**fields)


def _table(headers: tuple[str, ...], rows: list[tuple[str, ...]]) -> str:
    """Render a GitHub-flavoured Markdown table.

    Args:
        headers: The column headings.
        rows: The rows, each with one cell per heading.

    Returns:
        The Markdown table, ending in a newline.
    """
    lines = [
        "| " + " | ".join(headers) + " |",
        "| " + " | ".join("---" for _ in headers) + " |",
    ]
    lines.extend("| " + " | ".join(row) + " |" for row in rows)
    return "\n".join(lines) + "\n"


def schema_markdown() -> str:
    """Render the schema registry as Markdown.

    Returns:
        The contents of ``docs/schema.md``.
    """
    out = [
        "# Schema\n",
        _GENERATED_BANNER,
        (
            'Every `custom "envelope"` directive verb, metadata key and '
            "reserved value the plugin understands.\n"
        ),
        "## Directive verbs\n",
    ]
    for verb in DIRECTIVE_VERBS:
        out.append(f"### `{verb.verb}`\n")
        out.append(verb.description + "\n")
        if verb.positionals:
            out.append("")
            out.append(
                _table(
                    ("Argument", "Kind", "Required", "Description"),
                    [
                        (
                            f"`{arg.name}`",
                            str(arg.kind),
                            "yes" if arg.required else "no",
                            arg.description,
                        )
                        for arg in verb.positionals
                    ],
                )
            )
        keys = ", ".join(f"`{key}`" for key in verb.metadata) or "none"
        out.append(f"\nMetadata: {keys}.\n")

    out.append("## Metadata keys\n")
    out.append(
        _table(
            ("Key", "Kind", "Required", "Default", "Applies to", "Meaning"),
            [
                (
                    f"`{key.key}`",
                    str(key.kind),
                    "yes" if key.required else "no",
                    f"`{key.default}`" if key.default is not None else "—",
                    ", ".join(str(where) for where in key.applies_to),
                    key.description,
                )
                for key in METADATA_KEYS
            ],
        )
    )

    out.append("\n## Reserved values\n")
    out.append(
        _table(
            ("Value", "Meaning"),
            [(f"`{value.value}`", value.description) for value in RESERVED_VALUES],
        )
    )
    return "\n".join(out)


def errors_markdown() -> str:
    """Render the diagnostic registry as Markdown.

    Returns:
        The contents of ``docs/errors.md``.
    """
    out = [
        "# Errors and warnings\n",
        _GENERATED_BANNER,
        _table(
            ("Code", "Severity", "Condition"),
            [
                (f"`{code.code}`", str(code.severity), code.summary)
                for code in DIAGNOSTIC_CODES
            ],
        ),
    ]
    for code in DIAGNOSTIC_CODES:
        out.append(f"\n## {code.code}\n")
        out.append(f"**{code.severity.value.capitalize()}:** {code.summary}\n")
        out.append(code.explanation + "\n")
    return "\n".join(out)


def schema_as_json() -> dict[str, Any]:
    """Render the schema registry as plain JSON-serialisable data.

    Returns:
        A dictionary with ``directive_verbs``, ``metadata_keys`` and
        ``reserved_values`` keys.
    """
    return {
        "directive_verbs": [asdict(verb) for verb in DIRECTIVE_VERBS],
        "metadata_keys": [asdict(key) for key in METADATA_KEYS],
        "reserved_values": [asdict(value) for value in RESERVED_VALUES],
    }


def dump_schema_json() -> str:
    """Render the schema registry as a JSON string.

    Returns:
        The registry encoded as indented JSON, ending in a newline.
    """
    return json.dumps(schema_as_json(), indent=2) + "\n"
