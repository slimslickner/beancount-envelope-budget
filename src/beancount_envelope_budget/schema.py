"""The single source of truth for directives, metadata and diagnostics.

Two registries live here:

* the **schema registry**, describing every ``custom "envelope"`` verb,
  metadata key and reserved value the plugin understands, and
* the **diagnostic registry**, describing every error and warning code the
  plugin can emit.

Parsing, validation and the generated documentation all read these registries,
so the documentation cannot drift from behaviour.
"""

