def _compile_pattern(value: str | None, option: str) -> re.Pattern[str] | None:
    """Compile a regex filter from a command-line option.

    Args:
        value: The regular expression, or ``None``.
        option: The option name, for the error message.

    Returns:
        The compiled pattern, ``None`` when unfiltered, or
        :data:`_INVALID_PATTERN` on a bad expression.
    """
    if value is None:
        return None
    try:
        return re.compile(value)
    except re.error as error:
        print(f"invalid {option} pattern: {error}", file=sys.stderr)
        return _INVALID_PATTERN


def _last_day_of(month: date) -> date:
    """Return the last calendar day of a month.

    Args:
        month: Any date within the month.

    Returns:
        The last day of that month.
    """
    first = month_of(month)
    if first.month == _DECEMBER:
        return date(first.year, _DECEMBER, 31)
    return date(first.year, first.month + 1, 1) - timedelta(days=1)


def _shift_month(month: date, delta: int) -> date:
    """Shift a month by a signed number of months.

    Args:
        month: Any date within the month.
        delta: The number of months to shift, positive or negative.

    Returns:
        The first day of the shifted month.
    """
    index = month.year * 12 + (month.month - 1) + delta
    return date(index // 12, index % 12 + 1, 1)


def _maybe_row(rows: Sequence[MonthRow], month: date) -> MonthRow | None:
    """Return a monthly row, or ``None`` when the month is out of range.

    Args:
        rows: The rows to search.
        month: The month to find.

    Returns:
        The matching row, or ``None``.
    """
    return next((row for row in rows if row.month == month), None)


def _plan_fund(
    result: BudgetResult,
    entries: list[Directive],
    mode: str,
    requested: list[date],
    pattern: re.Pattern[str] | None,
    *,
    force: bool,
) -> list[Custom]:
    """Build the ``allocate`` directives for a range.

    Args:
        result: The computed budget.
        entries: The ledger entries, for detecting existing allocations.
        mode: One of ``actuals``, ``overspend`` or ``copy``.
        requested: The months to fund, ascending.
        pattern: An optional envelope-name filter.
        force: Whether to re-fund envelopes and months that already have an
            allocation directive.

    Returns:
        The directives, built through :mod:`beancount_envelope_budget.actions`.
    """
    currency = result.operating_currency
    existing = existing_allocations(entries)
    generated: dict[tuple[str, date], Decimal] = {}
    cumulative: dict[str, Decimal] = {}
    generated_entries: list[Custom] = []
    for month in requested:
        for report in result.envelopes:
            name = report.name
            if pattern is not None and not pattern.search(name):
                continue
            key = (name, month)
            if key in existing and not force:
                generated[key] = existing[key]
                continue
            amount = _fund_amount(mode, report, month, existing, generated, cumulative)
            if amount is None:
                continue
            generated[key] = amount
            if amount != 0:
                generated_entries.append(
                    actions.allocate(name, amount, _last_day_of(month), currency)
                )
    return generated_entries


def _fund_amount(
    mode: str,
    report: EnvelopeReport,
    month: date,
    existing: dict[tuple[str, date], Decimal],
    generated: dict[tuple[str, date], Decimal],
    cumulative: dict[str, Decimal],
) -> Decimal | None:
    """Compute a single month's allocation for one envelope.

    Args:
        mode: One of ``actuals``, ``overspend`` or ``copy``.
        report: The envelope's report.
        month: The month to fund.
        existing: Existing allocations from the ledger.
        generated: Allocations generated so far this run.
        cumulative: Running generated totals per envelope.

    Returns:
        The allocation, or ``None`` when the month has no data.
    """
    if mode == "copy":
        previous = generated.get((report.name, _shift_month(month, -1)))
        if previous is None:
            previous = existing.get((report.name, _shift_month(month, -1)))
        return previous
    row = _maybe_row(report.rows, month)
    if row is None:
        return None
    if mode == "actuals":
        return -row.activity
    balance = row.opening + cumulative.get(report.name, Decimal(0))
    allocation = max(Decimal(0), -(balance + row.activity))
    cumulative[report.name] = cumulative.get(report.name, Decimal(0)) + allocation
    return allocation


def _plan_topup(
    result: BudgetResult,
    on: date,
    reserve: Decimal,
    pattern: re.Pattern[str] | None,
) -> tuple[
    list[Custom],
    list[tuple[str, Decimal]],
    list[tuple[str, Decimal]],
]:
    """Plan a ``topup`` run.

    Args:
        result: The computed budget.
        on: The run date.
        reserve: Cash to keep unallocated in the pool.
        pattern: An optional envelope-name filter.

    Returns:
        The directives, the unfunded shortfalls, and the amounts by which goal
        envelopes already exceed their level.
    """
    currency = result.operating_currency
    remaining = row_for(result.pool, month_of(on)).closing - reserve
    candidates: list[tuple[bool, Decimal, int, str, Decimal]] = []
    overfunded: list[tuple[str, Decimal]] = []
    for index, report in enumerate(result.envelopes):
        envelope = report.envelope
        if pattern is not None and not pattern.search(envelope.name):
            continue
        plan = envelope.effective(on)
        level = plan_level(report, on)
        if level is None:
            continue
        balance = report.funded_at(on)
        need = (level - balance).quantize(_CENT, rounding=ROUND_CEILING)
        if need <= 0:
            excess = (balance - level).quantize(_CENT, rounding=ROUND_FLOOR)
            if plan.target is not None and excess > 0:
                overfunded.append((envelope.name, excess))
            continue
        rank = plan.priority if plan.priority is not None else Decimal(0)
        candidates.append((plan.priority is None, rank, index, envelope.name, need))
    candidates.sort(key=lambda item: (item[0], item[1], item[2]))

    lines: list[Custom] = []
    unfunded: list[tuple[str, Decimal]] = []
    for _unset, _rank, _index, name, need in candidates:
        if remaining <= 0:
            unfunded.append((name, need))
            continue
        amount = min(need, remaining)
        remaining -= amount
        lines.append(actions.allocate(name, amount, on, currency))
        if amount < need:
            unfunded.append((name, need - amount))
    return lines, unfunded, overfunded


def _parse_decimal(value: str) -> Decimal:
    """Parse a decimal argument.

    Args:
        value: The raw argument.

    Returns:
        The parsed decimal.

    Raises:
        argparse.ArgumentTypeError: If the value is not a number.
    """
    try:
        return Decimal(value)
    except ArithmeticError as error:
        message = f"expected a number, got {value!r}"
        raise argparse.ArgumentTypeError(message) from error


def _parse_monthly(value: str) -> Decimal | str:
    """Parse a ``--monthly`` argument: a number or ``avgN``.

    Args:
        value: The raw argument.

    Returns:
        The parsed decimal, or the ``avgN`` string.

    Raises:
        argparse.ArgumentTypeError: If the value is not a number or ``avgN``.
    """
    try:
        return Decimal(value)
    except ArithmeticError:
        if re.fullmatch(r"avg\d+", value):
            return value
        message = f"expected a number or avgN, got {value!r}"
        raise argparse.ArgumentTypeError(message) from None


def _parse_day(value: str) -> date:
    """Parse a ``YYYY-MM-DD`` argument.

    Args:
        value: The raw argument.

    Returns:
        The parsed date.

    Raises:
        argparse.ArgumentTypeError: If the value is not a date.
    """
    try:
        return date.fromisoformat(value)
    except ValueError as error:
        message = f"expected a date as YYYY-MM-DD, got {value!r}"
        raise argparse.ArgumentTypeError(message) from error


# --- Pinning -------------------------------------------------------------------


def _cmd_pin(args: argparse.Namespace) -> int:
    """Print a diff that freezes resolved envelopes onto existing postings.

    Args:
        args: Parsed arguments.

    Returns:
        The process exit status.
    """
    if not args.ledger.exists():
        print(f"no such ledger: {args.ledger}", file=sys.stderr)
        return 2
    pattern = _compile_pattern(args.account, "--account")
    if pattern is None or pattern is _INVALID_PATTERN:
        return 2
    loaded = _load(args.ledger, collect_resolved=True)
    if loaded.result.start is None:
        print("there is no start directive; nothing to pin", file=sys.stderr)
        return 0
    edits = _collect_pin_edits(
        loaded.entries, dict(loaded.result.resolved), pattern, args.through
    )
    if not edits:
        print("nothing to pin", file=sys.stderr)
        return 0
    if args.write:
        written = sum(
            _write_pin(filename, edits[filename]) for filename in sorted(edits)
        )
        print(f"pinned {written} posting(s) in {len(edits)} file(s)")
        return 0
    for filename in sorted(edits):
        sys.stdout.write(_pin_diff(filename, edits[filename]))
    return 0


def _collect_pin_edits(
    entries: list[Directive],
    resolved: dict[int, str],
    pattern: re.Pattern[str],
    through: date | None,
) -> dict[str, list[tuple[int, str]]]:
    """Select postings to pin and the lines to insert.

    Args:
        entries: The ledger entries.
        resolved: ``id(posting)`` to resolved envelope.
        pattern: The account filter.
        through: The latest date to pin, inclusive, or ``None``.

    Returns:
        A mapping from file name to ``(lineno, envelope)`` insertions.
    """
    edits: dict[str, list[tuple[int, str]]] = {}
    for entry in entries:
        if not isinstance(entry, Transaction):
            continue
        if through is not None and entry.date > through:
            continue
        for posting in entry.postings:
            name = resolved.get(id(posting))
            if name is None or not pattern.search(posting.account):
                continue
            meta = posting.meta or {}
            if "envelope" in meta:
                continue
            filename = meta.get("filename")
            if not isinstance(filename, str) or filename.startswith("<"):
                continue
            if not Path(filename).exists():
                continue
            edits.setdefault(filename, []).append((int(meta.get("lineno", 0)), name))
    return edits


def _read_lines(path: Path) -> list[str]:
    """Read a file's lines without translating line endings.

    Args:
        path: The file to read.

    Returns:
        The lines, each keeping its own line ending.
    """
    with path.open("r", encoding="utf-8", newline="") as handle:
        return handle.read().splitlines(keepends=True)


def _write_pin(filename: str, edits: list[tuple[int, str]]) -> int:
    """Apply the insertions to a file in place.

    Args:
        filename: The file to edit.
        edits: The ``(lineno, envelope)`` insertions.

    Returns:
        The number of insertions applied.
    """
    path = Path(filename)
    updated = _apply_insertions(_read_lines(path), edits)
    with path.open("w", encoding="utf-8", newline="") as handle:
        handle.write("".join(updated))
    return len(edits)


def _pin_diff(filename: str, edits: list[tuple[int, str]]) -> str:
    """Render the unified diff for one file.

    Args:
        filename: The file to edit.
        edits: The ``(lineno, envelope)`` insertions.

    Returns:
        The unified diff, or an empty string.
    """
    path = Path(filename)
    original = _read_lines(path)
    updated = _apply_insertions(original, edits)
    return "".join(
        difflib.unified_diff(
            original, updated, fromfile=str(path), tofile=f"{path} (pinned)"
        )
    )


def _apply_insertions(lines: list[str], edits: list[tuple[int, str]]) -> list[str]:
    """Insert ``envelope`` metadata lines into a file's lines.

    Args:
        lines: The file's lines, with line endings.
        edits: The ``(lineno, envelope)`` insertions.

    Returns:
        The new lines.
    """
    updated = list(lines)
    for lineno, name in sorted(edits, key=lambda edit: edit[0], reverse=True):
        posting_line = lines[lineno - 1] if 0 < lineno <= len(lines) else ""
        indent = _metadata_indent(lines, lineno, posting_line)
        updated.insert(
            lineno, f'{indent}envelope: "{name}"{_line_ending(posting_line)}'
        )
    return updated


def _metadata_indent(lines: list[str], lineno: int, posting_line: str) -> str:
    """Choose the indentation for an inserted metadata line.

    Args:
        lines: The file's lines.
        lineno: The posting's one-based line number.
        posting_line: The posting's own line.

    Returns:
        The existing metadata indentation when present, else two spaces beyond
        the posting's own indentation.
    """
    posting_indent = posting_line[: len(posting_line) - len(posting_line.lstrip())]
    index = lineno
    while index < len(lines):
        line = lines[index]
        if not line.strip():
            index += 1
            continue
        indent = line[: len(line) - len(line.lstrip())]
        if len(indent) > len(posting_indent):
            return indent
        break
    return posting_indent + "  "


def _line_ending(line: str) -> str:
    r"""Return the line ending used by a line.

    Args:
        line: A line, possibly with a line ending.

    Returns:
        ``"\r\n"`` when the line uses CRLF, else ``"\n"``.
    """
    return "\r\n" if line.endswith("\r\n") else "\n"


