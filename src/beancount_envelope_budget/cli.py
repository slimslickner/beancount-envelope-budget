def _cmd_fund(args: argparse.Namespace) -> int:
    """Print ``allocate`` directives for a range or a topup run.

    Args:
        args: Parsed arguments.

    Returns:
        The process exit status.
    """
    if not args.ledger.exists():
        print(f"no such ledger: {args.ledger}", file=sys.stderr)
        return 2
    pattern = _compile_pattern(args.envelopes, "--envelopes")
    if pattern is _INVALID_PATTERN:
        return 2
    loaded = _load(args.ledger)
    result = loaded.result
    if result.start is None:
        print("there is no start directive; nothing to fund", file=sys.stderr)
        return 0
    if args.mode == "topup":
        return _fund_topup(args, result, pattern)
    if args.mode in ("fully-fund", "fund-available"):
        return _fund_month(args, result, pattern)
    return _fund_range(args, loaded, pattern)


def _fund_month(
    args: argparse.Namespace,
    result: BudgetResult,
    pattern: re.Pattern[str] | None,
) -> int:
    """Run the ``fully-fund`` and ``fund-available`` month actions.

    Args:
        args: Parsed arguments.
        result: The computed budget.
        pattern: An optional envelope-name filter.

    Returns:
        The process exit status.
    """
    if args.from_month is not None or args.to_month is not None:
        print(f"--mode {args.mode} takes --date, not --from/--to", file=sys.stderr)
        return 2
    on = args.date or date.today()  # noqa: DTZ011 - local today is intended
    available = args.mode == "fund-available"
    allocations, unfunded = month_funding(
        result,
        on,
        available=available,
        reserve=args.reserve,
    )
    if pattern is not None:
        allocations = [
            (name, amount) for name, amount in allocations if pattern.search(name)
        ]
        unfunded = [(name, amount) for name, amount in unfunded if pattern.search(name)]
    currency = result.operating_currency
    day = _last_day_of(on)
    entries = [
        actions.allocate(name, amount, day, currency) for name, amount in allocations
    ]
    status = _emit(entries, args)
    for name, amount in unfunded:
        print(f"; UNFUNDED {name}: needs {_money(amount)} {currency}")
    return 1 if args.strict and unfunded else status


def _fund_topup(
    args: argparse.Namespace,
    result: BudgetResult,
    pattern: re.Pattern[str] | None,
) -> int:
    """Run the ``topup`` mode.

    Args:
        args: Parsed arguments.
        result: The computed budget.
        pattern: An optional envelope-name filter.

    Returns:
        The process exit status.
    """
    if args.from_month is not None or args.to_month is not None:
        print("--mode topup takes --date, not --from/--to", file=sys.stderr)
        return 2
    on = args.date or date.today()  # noqa: DTZ011 - local today is intended
    lines, unfunded, overfunded = _plan_topup(result, on, args.reserve, pattern)
    status = _emit(lines, args)
    for name, amount in unfunded:
        print(f"; UNFUNDED {name}: needs {_money(amount)} {result.operating_currency}")
    for name, amount in overfunded:
        print(
            f"; OVERFUNDED {name}: {_money(amount)} "
            f"{result.operating_currency} above plan"
        )
    return 1 if args.strict and unfunded else status


def _fund_range(
    args: argparse.Namespace,
    loaded: _Loaded,
    pattern: re.Pattern[str] | None,
) -> int:
    """Run the ``actuals``, ``overspend`` or ``copy`` mode over a month range.

    Args:
        args: Parsed arguments.
        loaded: The loaded ledger and its budget.
        pattern: An optional envelope-name filter.

    Returns:
        The process exit status.
    """
    if args.date is not None:
        print(
            "--date is only valid with --mode topup, fully-fund or fund-available",
            file=sys.stderr,
        )
        return 2
    if args.from_month is None or args.to_month is None:
        print("--from and --to are required for this mode", file=sys.stderr)
        return 2
    if args.from_month > args.to_month:
        print("--from must not be after --to", file=sys.stderr)
        return 2
    requested = iter_months(args.from_month, args.to_month)
    entries = _plan_fund(
        loaded.result,
        loaded.entries,
        args.mode,
        requested,
        pattern,
        force=args.force,
    )
    return _emit(entries, args)


def _emit(entries: list[Custom], args: argparse.Namespace) -> int:
    """Print generated directives, or append them to ``--write`` and recheck.

    Args:
        entries: The generated directives.
        args: Parsed arguments; ``args.ledger`` and the optional ``args.write``.

    Returns:
        The process exit status.
    """
    if args.write is None:
        for entry in entries:
            print(actions.render(entry))
        return 0
    try:
        target = writer.resolve_target(args.write, args.ledger.parent)
    except ValueError as error:
        print(str(error), file=sys.stderr)
        return 2
    for entry in entries:
        writer.append(target, entry)
    print(f"appended {len(entries)} directive(s) to {target}")
    return _recheck(args.ledger)


def _recheck(path: Path) -> int:
    """Reload a ledger after a write and report any diagnostics.

    Args:
        path: The ledger path.

    Returns:
        The process exit status: non-zero when the reload produces an error.
    """
    loaded = _load(path)
    errors = [
        diagnostic
        for diagnostic in loaded.result.diagnostics
        if diagnostic.severity is Severity.ERROR
    ]
    warnings = [
        diagnostic
        for diagnostic in loaded.result.diagnostics
        if diagnostic.severity is Severity.WARNING
    ]
    for diagnostic in [*errors, *warnings]:
        print(f"{diagnostic.code}: {diagnostic.message}")
    return 1 if errors else 0


