def _walk_commands(
    parser: argparse.ArgumentParser,
    path: tuple[str, ...],
) -> list[tuple[tuple[str, ...], argparse.ArgumentParser]]:
    """Collect a parser and its subcommands, depth first.

    Args:
        parser: The parser to walk.
        path: The command path leading to ``parser``.

    Returns:
        A list of ``(path, parser)`` pairs, parents before children.
    """
    found = [(path, parser)]
    for action in parser._actions:  # noqa: SLF001
        if isinstance(action, argparse._SubParsersAction):  # noqa: SLF001
            for name, subparser in action.choices.items():
                found.extend(_walk_commands(subparser, (*path, name)))
    return found


def _usage_of(action: argparse.Action) -> str:
    """Render the invocation text for an argument.

    Args:
        action: The argument's parser action.

    Returns:
        The option strings, or the destination for a positional argument.
    """
    if action.option_strings:
        return ", ".join(action.option_strings)
    return action.dest


def cli_markdown(parser: argparse.ArgumentParser) -> str:
    """Render the argument parser tree as Markdown.

    Args:
        parser: The root parser to document.

    Returns:
        The contents of ``docs/cli.md``.
    """
    out = [
        "# CLI reference\n",
        _GENERATED_BANNER + "\n",
        (
            "Every subcommand and flag, generated from the argument parser. "
            "`--help` is the source of truth.\n"
        ),
    ]
    for path, current in _walk_commands(parser, ("beancount-envelope-budget",)):
        heading = " ".join(path)
        out.append(f"## `{heading}`\n")
        if current.description:
            out.append(current.description + "\n")
        rows = [
            (f"`{_usage_of(action)}`", action.help or "")
            for action in current._actions  # noqa: SLF001
            if not isinstance(action, argparse._SubParsersAction)  # noqa: SLF001
        ]
        out.append("")
        out.append(_options_table(rows))
    return "\n".join(out)


def _options_table(rows: list[tuple[str, str]]) -> str:
    """Render an options table.

    Args:
        rows: ``(usage, help)`` pairs.

    Returns:
        The Markdown table, ending in a newline.
    """
    lines = ["| Option | Help |", "| --- | --- |"]
    lines.extend(f"| {usage} | {help_text} |" for usage, help_text in rows)
    return "\n".join(lines) + "\n"


def render_docs() -> dict[str, str]:
    """Render every generated documentation file.

    Returns:
        A mapping from file name to Markdown contents, matching
        :data:`_GENERATED_FILES`.
    """
    return {
        "cli.md": cli_markdown(build_parser()),
        "schema.md": schema_markdown(),
        "errors.md": errors_markdown(),
    }


def main(argv: Sequence[str] | None = None) -> int:
    """Run the command line interface.

    Args:
        argv: Command line arguments, excluding the program name. Defaults to
            :data:`sys.argv`.

    Returns:
        The process exit status.
    """
    parser = build_parser()
    argcomplete.autocomplete(parser)
    args = parser.parse_args(argv)
    handler: Callable[[argparse.Namespace], int] = args.func
    return handler(args)


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
