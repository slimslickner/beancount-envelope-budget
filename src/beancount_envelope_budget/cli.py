"""The ``beancount-envelope-budget`` command line interface.

A thin ``argparse`` front end over :mod:`beancount_envelope_budget.core`. The
full command tree grows across milestones; ``schema`` and ``docs`` exist from
the start so the generated documentation and its ``--check`` gate are in place
before the behaviour they describe.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import TYPE_CHECKING

from beancount_envelope_budget.schema import (
    dump_schema_json,
    errors_markdown,
    schema_markdown,
)

if TYPE_CHECKING:
    from collections.abc import Sequence

__all__ = ["build_parser", "cli_markdown", "main", "render_docs"]

_GENERATED_BANNER = (
    "> Generated by `beancount-envelope-budget docs`. Do not edit by hand."
)

_GENERATED_FILES = ("cli.md", "schema.md", "errors.md")


def _repo_root() -> Path:
    """Return the repository root, inferred from this module's location.

    Returns:
        The directory two levels above the package directory.
    """
    return Path(__file__).resolve().parents[2]


def _docs_dir() -> Path:
    """Return the directory that holds the generated documentation.

    Returns:
        The ``docs`` directory at the repository root.
    """
    return _repo_root() / "docs"


def build_parser() -> argparse.ArgumentParser:
    """Build the full argument parser.

    Returns:
        The configured :class:`argparse.ArgumentParser` with every subcommand
        and flag registered.
    """
    parser = argparse.ArgumentParser(
        prog="beancount-envelope-budget",
        description="Ledger-driven envelope budgeting for Beancount.",
    )
    parser.add_argument(
        "--version",
        action="version",
        version="%(prog)s 0.0.1",
        help="show the program version and exit",
    )
    subparsers = parser.add_subparsers(
        dest="command",
        metavar="COMMAND",
        required=True,
    )

    schema = subparsers.add_parser(
        "schema",
        help="print the directive, metadata and reserved-value schema",
        description=(
            "Print every directive, metadata key and reserved value the "
            "plugin understands, from the schema registry."
        ),
    )
    schema.add_argument(
        "--json",
        action="store_true",
        help="print the schema as JSON instead of Markdown",
    )
    schema.set_defaults(func=_cmd_schema)

    docs = subparsers.add_parser(
        "docs",
        help="regenerate the generated documentation",
        description=(
            "Regenerate docs/cli.md, docs/schema.md and docs/errors.md. With "
            "--check, write nothing and exit non-zero if any is out of date."
        ),
    )
    docs.add_argument(
        "--check",
        action="store_true",
        help="write nothing and exit non-zero if any generated file is stale",
    )
    docs.set_defaults(func=_cmd_docs)

    return parser


def _cmd_schema(args: argparse.Namespace) -> int:
    """Print the schema registry.

    Args:
        args: Parsed arguments; ``args.json`` selects the output format.

    Returns:
        The process exit status.
    """
    sys.stdout.write(dump_schema_json() if args.json else schema_markdown())
    return 0


def _cmd_docs(args: argparse.Namespace) -> int:
    """Write or check the generated documentation.

    Args:
        args: Parsed arguments; ``args.check`` selects check-only mode.

    Returns:
        The process exit status.
    """
    docs_dir = _docs_dir()
    generated = render_docs()
    if args.check:
        stale = [
            name
            for name, content in generated.items()
            if _read(docs_dir / name) != content
        ]
        for name in stale:
            print(f"out of date: docs/{name}", file=sys.stderr)
        if stale:
            print(
                "run `beancount-envelope-budget docs` to regenerate",
                file=sys.stderr,
            )
            return 1
        print("generated docs are up to date")
        return 0

    docs_dir.mkdir(parents=True, exist_ok=True)
    for name, content in generated.items():
        (docs_dir / name).write_text(content, encoding="utf-8")
        print(f"wrote docs/{name}")
    return 0


def _read(path: Path) -> str | None:
    """Read a text file if it exists.

    Args:
        path: The file to read.

    Returns:
        The file's contents, or ``None`` when it does not exist.
    """
    return path.read_text(encoding="utf-8") if path.exists() else None


def _walk_commands(
    parser: argparse.ArgumentParser,
    path: tuple[str, ...],
) -> list[tuple[tuple[str, ...], argparse.ArgumentParser]]:
    """Collect a parser and its subcommands, depth first.

    Args:
        parser: The parser to walk.
        path: The command path leading to ``parser``.

    Returns:
        A list of ``(path, parser)`` pairs, parents before children.
    """
    found = [(path, parser)]
    for action in parser._actions:  # noqa: SLF001
        if isinstance(action, argparse._SubParsersAction):  # noqa: SLF001
            for name, subparser in action.choices.items():
                found.extend(_walk_commands(subparser, (*path, name)))
    return found


def _usage_of(action: argparse.Action) -> str:
    """Render the invocation text for an argument.

    Args:
        action: The argument's parser action.

    Returns:
        The option strings, or the destination for a positional argument.
    """
    if action.option_strings:
        return ", ".join(action.option_strings)
    return action.dest


def cli_markdown(parser: argparse.ArgumentParser) -> str:
    """Render the argument parser tree as Markdown.

    Args:
        parser: The root parser to document.

    Returns:
        The contents of ``docs/cli.md``.
    """
    out = [
        "# CLI reference\n",
        _GENERATED_BANNER + "\n",
        (
            "Every subcommand and flag, generated from the argument parser. "
            "`--help` is the source of truth.\n"
        ),
    ]
    for path, current in _walk_commands(parser, ("beancount-envelope-budget",)):
        heading = " ".join(path)
        out.append(f"## `{heading}`\n")
        if current.description:
            out.append(current.description + "\n")
        rows = [
            (f"`{_usage_of(action)}`", action.help or "")
            for action in current._actions  # noqa: SLF001
            if not isinstance(action, argparse._SubParsersAction)  # noqa: SLF001
        ]
        out.append("")
        out.append(_options_table(rows))
    return "\n".join(out)


def _options_table(rows: list[tuple[str, str]]) -> str:
    """Render an options table.

    Args:
        rows: ``(usage, help)`` pairs.

    Returns:
        The Markdown table, ending in a newline.
    """
    lines = ["| Option | Help |", "| --- | --- |"]
    lines.extend(f"| {usage} | {help_text} |" for usage, help_text in rows)
    return "\n".join(lines) + "\n"


def render_docs() -> dict[str, str]:
    """Render every generated documentation file.

    Returns:
        A mapping from file name to Markdown contents, matching
        :data:`_GENERATED_FILES`.
    """
    return {
        "cli.md": cli_markdown(build_parser()),
        "schema.md": schema_markdown(),
        "errors.md": errors_markdown(),
    }


def main(argv: Sequence[str] | None = None) -> int:
    """Run the command line interface.

    Args:
        argv: Command line arguments, excluding the program name. Defaults to
            :data:`sys.argv`.

    Returns:
        The process exit status.
    """
    parser = build_parser()
    args = parser.parse_args(argv)
    return args.func(args)


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
