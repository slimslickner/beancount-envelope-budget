"""The all-features sample ledger stays current and every feature works.

``tests/ledgers/sample.bean`` is generated by ``scripts/sample_ledger.py``. The
first test keeps the committed file in step with the generator, so adding a
feature means extending the generator; the rest load the sample through the same
core the CLI and the Fava report use and assert the feature each part shows.
"""

from __future__ import annotations

from datetime import date
from decimal import Decimal

from beancount import loader
from sample_ledger import DEFAULT_OUT, build

from beancount_envelope_budget.core import BudgetResult, compute
from beancount_envelope_budget.report import build_view


def test_sample_is_current() -> None:
    """The committed sample is exactly what the generator produces."""
    assert DEFAULT_OUT.read_text(encoding="utf-8") == build()


def test_sample_loads_clean() -> None:
    """The sample has no Beancount errors and no budget diagnostics."""
    entries, errors, options = loader.load_file(DEFAULT_OUT)
    assert not errors, [error.message for error in errors]
    result = compute(entries, options)
    assert result.diagnostics == ()


def test_sample_holds_the_invariant() -> None:
    """Pool plus envelopes equals cash at every month end."""
    result = _result()
    for pool_row, cash_row in zip(result.pool, result.cash, strict=True):
        total = pool_row.closing + sum(
            (report.closing_at(pool_row.month) for report in result.envelopes),
            Decimal(0),
        )
        assert total == cash_row.balance


def test_sample_covers_the_plan_kinds() -> None:
    """Every plan kind is present and resolves through ``effective``."""
    result = _result()
    a = date(2024, 6, 30)
    assert _envelope(result, "Groceries").envelope.effective(a).monthly is None
    assert _envelope(result, "Rent").envelope.effective(a).monthly is not None
    assert _envelope(result, "Utilities").envelope.effective(a).up_to is not None
    assert _envelope(result, "Dining").envelope.effective(a).monthly == "avg3"
    emergency = _envelope(result, "Emergency").envelope.effective(a)
    assert emergency.goal is not None
    assert emergency.by is not None


def test_sample_goal_is_met_then_spent_and_closed() -> None:
    """Laptop is funded, spent out of, and closed at zero; Vacation is spent."""
    result = _result()
    laptop = _envelope(result, "Laptop")
    assert laptop.closing == 0
    assert laptop.envelope.closed == date(2024, 5, 1)

    vacation = _envelope(result, "Vacation")
    assert vacation.closing == 0
    assert vacation.envelope.closed is None
    # A goal met by contributions still reads as funded after it is spent.
    assert vacation.funded_at(date(2024, 6, 30)) == 3000


def test_sample_late_open_is_hidden_before_it_opens() -> None:
    """Gym opens in March, so it is hidden in the first two months."""
    view = build_view(_result(), date(2024, 1, 1), 2)
    assert not _view(view, "Gym").visible


def test_sample_close_is_hidden_after_it_closes() -> None:
    """Moving closes in March, so it is gone from the months after."""
    view = build_view(_result(), date(2024, 4, 1), 1)
    assert not _view(view, "Moving").visible


def test_sample_overrides_land_in_their_envelope() -> None:
    """Costco counts against Groceries; the overrides land in Gifts and Fun."""
    result = _result()
    assert _envelope(result, "Groceries").closing == 180
    assert _envelope(result, "Gifts").closing == 90
    assert _envelope(result, "Fun").closing == 60


def _result() -> BudgetResult:
    """Load and compute the sample with the default collection flags."""
    entries, _errors, options = loader.load_file(DEFAULT_OUT)
    return compute(entries, options)


def _envelope(result: BudgetResult, name: str):
    """Return an envelope report, asserting it exists."""
    report = result.envelope(name)
    assert report is not None, name
    return report


def _view(view, name: str):
    """Return an envelope view, asserting it exists."""
    found = next((item for item in view.envelopes if item.name == name), None)
    assert found is not None, name
    return found
